"""Independent symbolic check of the Angle Lemma (2026-09-05).
Four lines y = m_i x + c_i, pairwise non-parallel, no three concurrent. P_ij = L_i ∩ L_j.
Claim: the three diagonal quadruples {P12,P34,P13,P24}, {P12,P34,P14,P23}, {P13,P24,P14,P23}
are never all concyclic.
Method: WLOG (rotation) m_1 = 0, and (translation) c_1 = 0; then L_1 is the x-axis.
Concyclicity of 4 points = vanishing of the 4x4 determinant |x^2+y^2, x, y, 1|.
We show that the ideal generated by the three determinants, saturated by the non-degeneracy
conditions (m_i distinct, no three lines concurrent), contains 1 — i.e. the system is inconsistent.
Also we show directly: det1 and det2 imply m_2*m_3 = -1 ... etc., replicating the angle argument.
"""
import sympy as sp
m2, m3, m4, c2, c3, c4, t = sp.symbols('m2 m3 m4 c2 c3 c4 t')
m1, c1 = sp.Integer(0), sp.Integer(0)
L = {1: (m1, c1), 2: (m2, c2), 3: (m3, c3), 4: (m4, c4)}
def P(i, j):
    mi, ci = L[i]; mj, cj = L[j]
    x = (cj - ci) / (mi - mj)
    return (x, mi * x + ci)
def concyc(pts):
    M = sp.Matrix([[x**2 + y**2, x, y, 1] for x, y in pts])
    return sp.together(M.det())
Q = [[P(1,2), P(3,4), P(1,3), P(2,4)], [P(1,2), P(3,4), P(1,4), P(2,3)], [P(1,3), P(2,4), P(1,4), P(2,3)]]
dets = [sp.factor(sp.numer(sp.together(concyc(q)))) for q in Q]
for i, d in enumerate(dets):
    print(f"det{i+1} factors: {d}")
# non-degeneracy: distinct slopes; no three concurrent. Extract the 'essential' factors
# (those not among slope differences / concurrency conditions) and check inconsistency.
import itertools
nondeg = [m2, m3, m4, m2 - m3, m2 - m4, m3 - m4]
# concurrency of lines i,j,k: P_ij on L_k
for i, j, k in itertools.combinations([1,2,3,4], 3):
    x, y = P(i, j); mk, ck = L[k]
    nondeg.append(sp.numer(sp.together(y - (mk * x + ck))))
gens = [m2, m3, m4, c2, c3, c4, t]
# Rabinowitsch trick: 1 - t * prod(nondeg)
prod = sp.Integer(1)
for f in nondeg: prod *= f
G = sp.groebner(dets + [1 - t * prod], *gens, order='grevlex')
print("Groebner basis of (dets) + nondegeneracy saturation:", G.exprs)
print("INCONSISTENT (lemma holds)" if G.exprs == [1] else "NOT PROVED by this route")
