"""Core numerics for the symmetric-orbit search (Erdos #506).

A configuration is a union of orbits of the dihedral group D_m acting on the plane:
  ('A', r)        regular m-gon, vertices at angles 2*pi*k/m            (on mirror axes of type A)
  ('B', r)        regular m-gon, vertices at angles (2k+1)*pi/m         (on mirror axes of type B)
  ('G', r, th)    generic orbit of 2m points at angles +-th + 2*pi*k/m   (0 < th < pi/m)
  ('C',)          the centre
  ('I',)          the point at infinity (Moebius point; realised after inversion)

Moebius count: blocks = circles/lines through >= 3 points (lines through 2 finite points + infinity
count as blocks if 'I' is present).  circles(inv_O(P)) = |B| - deg(O) for an inversion centre O
not in P; O = infinity allowed iff 'I' not in P and gives the Euclidean count of P itself.
"""
import math, itertools
import numpy as np
from collections import defaultdict

TOL = 1e-7          # coincidence tolerance for block keys
OTOL = 1e-6         # tolerance for a candidate inversion centre lying on a block


# ----------------------------------------------------------------------------- configurations
def gen_points(m, orbits, params):
    """params: flat list of continuous parameters consumed in order by the orbits.
    Returns (pts ndarray (n,2), has_inf, labels); labels carry the orbit index."""
    pts = []; labels = []; k = 0; has_inf = False
    for oi, ob in enumerate(orbits):
        t = ob[0]
        if t == 'A':
            r = params[k]; k += 1
            for j in range(m):
                a = 2 * math.pi * j / m
                pts.append((r * math.cos(a), r * math.sin(a))); labels.append(('A', oi, j))
        elif t == 'B':
            r = params[k]; k += 1
            for j in range(m):
                a = (2 * j + 1) * math.pi / m
                pts.append((r * math.cos(a), r * math.sin(a))); labels.append(('B', oi, j))
        elif t == 'G':
            r, th = params[k], params[k + 1]; k += 2
            for j in range(m):
                for s in (1, -1):
                    a = s * th + 2 * math.pi * j / m
                    pts.append((r * math.cos(a), r * math.sin(a))); labels.append(('G', oi, j, s))
        elif t == 'R':
            r, th = params[k], params[k + 1]; k += 2
            for j in range(m):
                a = th + 2 * math.pi * j / m
                pts.append((r * math.cos(a), r * math.sin(a))); labels.append(('R', oi, j))
        elif t == 'C':
            pts.append((0.0, 0.0)); labels.append(('C', oi))
        elif t == 'I':
            has_inf = True
        else:
            raise ValueError(t)
    return np.array(pts, dtype=float), has_inf, labels


def nparams(orbits):
    return sum({'A': 1, 'B': 1, 'G': 2, 'R': 2, 'C': 0, 'I': 0}[o[0]] for o in orbits)


def group_perms(m, orbits):
    """Permutations of the finite point indices induced by the generators of the symmetry group
    (rotation by 2pi/m, and the reflection in the x-axis when no R orbit is present)."""
    _, _, labels = gen_points(m, orbits, [1.0 + 0.1 * i for i in range(nparams(orbits))])
    idx = {lab: i for i, lab in enumerate(labels)}
    assert len(idx) == len(labels)
    def rot(lab):
        if lab[0] in 'ABR': return (lab[0], lab[1], (lab[2] + 1) % m)
        if lab[0] == 'G': return ('G', lab[1], (lab[2] + 1) % m, lab[3])
        return lab
    def ref(lab):
        if lab[0] == 'A': return ('A', lab[1], (-lab[2]) % m)
        if lab[0] == 'B': return ('B', lab[1], (-lab[2] - 1) % m)
        if lab[0] == 'G': return ('G', lab[1], (-lab[2]) % m, -lab[3])
        return lab
    perms = [np.array([idx[rot(l)] for l in labels])]
    if not any(o[0] == 'R' for o in orbits):
        perms.append(np.array([idx[ref(l)] for l in labels]))
    for p in perms:
        assert sorted(p.tolist()) == list(range(len(labels)))
    return perms, labels


def orbit_reps(subsets, perms):
    """Representatives of the orbits of the group generated by perms on a list of index tuples."""
    seen = set(); reps = []
    subsets = [tuple(sorted(s)) for s in subsets]
    sset = set(subsets)
    for s in subsets:
        if s in seen: continue
        reps.append(s)
        # BFS orbit
        stack = [s]; seen.add(s)
        while stack:
            u = stack.pop()
            for p in perms:
                v = tuple(sorted(int(p[i]) for i in u))
                if v not in seen:
                    seen.add(v); stack.append(v)
    return reps


# ----------------------------------------------------------------------------- determinants
def concyc_dets(pts, quads):
    """Vectorised concyclicity determinant for index array quads (k,4); normalised by scale."""
    P = pts[quads]                     # (k,4,2)
    x = P[..., 0]; y = P[..., 1]
    M = np.stack([x, y, x * x + y * y, np.ones_like(x)], axis=-1)   # (k,4,4)
    d = np.linalg.det(M)
    # normalisation: product of pairwise distances scale ~ L^4 ; use L = max spread
    return d


def collin_dets(pts, trips):
    P = pts[trips]
    x = P[..., 0]; y = P[..., 1]
    return (x[:, 1] - x[:, 0]) * (y[:, 2] - y[:, 0]) - (x[:, 2] - x[:, 0]) * (y[:, 1] - y[:, 0])


# ----------------------------------------------------------------------------- blocks
def block_key(pts, i, j, k):
    (ax, ay), (bx, by), (cx, cy) = pts[i], pts[j], pts[k]
    d = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    scale = max(abs(ax - bx), abs(ay - by), abs(ax - cx), abs(ay - cy), 1e-300)
    if abs(d) < 1e-9 * scale * scale:
        A = by - ay; B = ax - bx; C = A * ax + B * ay
        nrm = math.hypot(A, B); A /= nrm; B /= nrm; C /= nrm
        if A < -1e-12 or (abs(A) < 1e-12 and B < 0): A, B, C = -A, -B, -C
        return ('L', round(A / TOL), round(B / TOL), round(C / TOL))
    a2 = ax * ax + ay * ay; b2 = bx * bx + by * by; c2 = cx * cx + cy * cy
    ux = (a2 * (by - cy) + b2 * (cy - ay) + c2 * (ay - by)) / d
    uy = (a2 * (cx - bx) + b2 * (ax - cx) + c2 * (bx - ax)) / d
    r = math.hypot(ax - ux, ay - uy)
    return ('C', round(ux / TOL), round(uy / TOL), round(r / TOL))


def blocks_of(pts, has_inf=False):
    """dict key -> set of finite point indices (index -1 stands for infinity)."""
    n = len(pts)
    Bl = defaultdict(set)
    for i, j, k in itertools.combinations(range(n), 3):
        Bl[block_key(pts, i, j, k)].update((i, j, k))
    if has_inf:
        # every line through >= 2 finite points is a block containing infinity
        for i, j in itertools.combinations(range(n), 2):
            (ax, ay), (bx, by) = pts[i], pts[j]
            A = by - ay; B = ax - bx; C = A * ax + B * ay
            nrm = math.hypot(A, B); A /= nrm; B /= nrm; C /= nrm
            if A < -1e-12 or (abs(A) < 1e-12 and B < 0): A, B, C = -A, -B, -C
            Bl[('L', round(A / TOL), round(B / TOL), round(C / TOL))].update((i, j, -1))
        for key in list(Bl):
            if key[0] == 'L': Bl[key].add(-1)
    return Bl


def block_geom(key):
    if key[0] == 'L':
        return ('L', key[1] * TOL, key[2] * TOL, key[3] * TOL)
    return ('C', key[1] * TOL, key[2] * TOL, key[3] * TOL)


def precise_geom(pts, members):
    """Full-precision geometry of the block through the given (finite) member indices."""
    mem = [i for i in members if i >= 0]
    if len(mem) == 2:      # line through 2 finite points (+ infinity)
        (ax, ay), (bx, by) = pts[mem[0]], pts[mem[1]]
        A = by - ay; B = ax - bx; C = A * ax + B * ay
        nrm = math.hypot(A, B)
        return ('L', A / nrm, B / nrm, C / nrm)
    i, j, k = mem[:3]
    (ax, ay), (bx, by), (cx, cy) = pts[i], pts[j], pts[k]
    d = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    scale = max(abs(ax - bx), abs(ay - by), abs(ax - cx), abs(ay - cy), 1e-300)
    if abs(d) < 1e-9 * scale * scale:
        A = by - ay; B = ax - bx; C = A * ax + B * ay
        nrm = math.hypot(A, B)
        return ('L', A / nrm, B / nrm, C / nrm)
    a2 = ax * ax + ay * ay; b2 = bx * bx + by * by; c2 = cx * cx + cy * cy
    ux = (a2 * (by - cy) + b2 * (cy - ay) + c2 * (ay - by)) / d
    uy = (a2 * (cx - bx) + b2 * (ax - cx) + c2 * (bx - ax)) / d
    return ('C', ux, uy, math.hypot(ax - ux, ay - uy))


def intersections(g1, g2):
    out = []
    if g1[0] == 'L' and g2[0] == 'L':
        _, A1, B1, C1 = g1; _, A2, B2, C2 = g2
        det = A1 * B2 - A2 * B1
        if abs(det) < 1e-9: return out
        return [((C1 * B2 - C2 * B1) / det, (A1 * C2 - A2 * C1) / det)]
    if g1[0] == 'L': g1, g2 = g2, g1
    _, cx, cy, r = g1
    if g2[0] == 'L':
        _, A, B, C = g2
        d = A * cx + B * cy - C
        if abs(d) > r + 1e-9: return out
        h = math.sqrt(max(r * r - d * d, 0.0))
        px, py = cx - A * d, cy - B * d
        return [(px - B * h, py + A * h), (px + B * h, py - A * h)]
    _, dx, dy, r2 = g2
    D = math.hypot(dx - cx, dy - cy)
    if D < 1e-9 or D > r + r2 + 1e-9 or D < abs(r - r2) - 1e-9: return out
    a = (r * r - r2 * r2 + D * D) / (2 * D)
    h = math.sqrt(max(r * r - a * a, 0.0))
    mx, my = cx + a * (dx - cx) / D, cy + a * (dy - cy) / D
    return [(mx + h * (dy - cy) / D, my - h * (dx - cx) / D), (mx - h * (dy - cy) / D, my + h * (dx - cx) / D)]


def on_block(g, x, y, tol=OTOL):
    if g[0] == 'L':
        return abs(g[1] * x + g[2] * y - g[3]) < tol
    return abs(math.hypot(x - g[1], y - g[2]) - g[3]) < tol


def evaluate(pts, has_inf=False, want_O=True, max_blocks_for_O=2600):
    """Return dict(best, euclid, nblocks, O, sizes, lines, deg) or None if degenerate
    (coincident points, or all points on one block)."""
    pts = np.asarray(pts, float)
    n = len(pts)
    # coincident points
    d2 = ((pts[:, None, :] - pts[None, :, :]) ** 2).sum(-1)
    np.fill_diagonal(d2, 1.0)
    if d2.min() < 1e-12: return None
    if not np.all(np.isfinite(pts)) or np.abs(pts).max() > 1e6: return None
    Bl = blocks_of(pts, has_inf)
    N = n + (1 if has_inf else 0)
    if any(len(s) == N for s in Bl.values()): return None
    nb = len(Bl)
    keys = list(Bl.keys())
    nlines = sum(1 for k in keys if k[0] == 'L')
    euclid = nb - nlines if not has_inf else None
    sizes = sorted((len(Bl[k]) for k in keys), reverse=True)
    res = {'nblocks': nb, 'sizes': sizes, 'lines': nlines, 'euclid': euclid}
    bestdeg = nlines if not has_inf else -1
    bestO = 'inf' if not has_inf else None
    if want_O and nb <= max_blocks_for_O:
        geoms = [precise_geom(pts, Bl[k]) for k in keys]
        cand = defaultdict(set)
        for i in range(nb):
            for j in range(i + 1, nb):
                for (x, y) in intersections(geoms[i], geoms[j]):
                    cand[(round(x / 1e-5), round(y / 1e-5))].update((i, j))
        # only candidates on >= 3 blocks (appear from >= 2 pairs) can beat... keep all with >=2
        for kk, s in cand.items():
            if len(s) <= bestdeg: continue
            x, y = kk[0] * 1e-5, kk[1] * 1e-5
            # refine the candidate point using two of its blocks (recompute intersection precisely)
            ii = sorted(s)
            best_pt = None
            for (x2, y2) in intersections(geoms[ii[0]], geoms[ii[1]]):
                if abs(x2 - x) < 1e-4 and abs(y2 - y) < 1e-4: best_pt = (x2, y2)
            if best_pt is None: continue
            x, y = best_pt
            if np.min(np.hypot(pts[:, 0] - x, pts[:, 1] - y)) < 1e-5: continue   # O in P
            deg = sum(1 for g in geoms if on_block(g, x, y))
            if deg > bestdeg:
                bestdeg = deg; bestO = (x, y)
                res['O_blocks'] = [sorted(Bl[keys[t]]) for t in range(nb) if on_block(geoms[t], x, y)]
    res['deg'] = bestdeg; res['O'] = bestO
    res['best'] = nb - bestdeg
    return res


def formula(n):
    return (n - 1) * (n - 2) // 2 + 1 - (n - 1) // 2


def invert(pts, O, R2=1.0):
    pts = np.asarray(pts, float); O = np.asarray(O, float)
    d = pts - O
    return O + R2 * d / (d * d).sum(-1)[:, None]


def realise(pts, has_inf, O):
    """Euclidean point set realising the best count: invert about O (finite), adding O for 'I'."""
    if O == 'inf' or O is None:
        assert not has_inf
        return np.asarray(pts, float)
    Q = invert(pts, O)
    if has_inf:
        Q = np.vstack([Q, np.asarray(O, float)[None, :]])
    return Q


# ----------------------------------------------------------------------------- fast O search
def _pair_intersections_vec(C, L):
    """C: (nc,3) circles (cx,cy,r); L: (nl,3) lines (A,B,C) unit normal.  Returns array (k,2) of all
    pairwise intersection points (each unordered pair contributes its points)."""
    out = []
    nc, nl = len(C), len(L)
    if nc >= 2:
        i, j = np.triu_indices(nc, 1)
        cx, cy, r = C[i, 0], C[i, 1], C[i, 2]
        dx, dy, r2 = C[j, 0], C[j, 1], C[j, 2]
        D = np.hypot(dx - cx, dy - cy)
        ok = (D > 1e-9) & (D <= r + r2 + 1e-9) & (D >= np.abs(r - r2) - 1e-9)
        cx, cy, r, dx, dy, r2, D = (v[ok] for v in (cx, cy, r, dx, dy, r2, D))
        a = (r * r - r2 * r2 + D * D) / (2 * D)
        h = np.sqrt(np.maximum(r * r - a * a, 0.0))
        mx, my = cx + a * (dx - cx) / D, cy + a * (dy - cy) / D
        ux, uy = (dy - cy) / D, (dx - cx) / D
        out.append(np.stack([mx + h * ux, my - h * uy], -1))
        out.append(np.stack([mx - h * ux, my + h * uy], -1))
    if nc >= 1 and nl >= 1:
        i, j = np.meshgrid(np.arange(nc), np.arange(nl), indexing='ij')
        i = i.ravel(); j = j.ravel()
        cx, cy, r = C[i, 0], C[i, 1], C[i, 2]
        A, B, Cc = L[j, 0], L[j, 1], L[j, 2]
        d = A * cx + B * cy - Cc
        ok = np.abs(d) <= r + 1e-9
        cx, cy, r, A, B, d = (v[ok] for v in (cx, cy, r, A, B, d))
        h = np.sqrt(np.maximum(r * r - d * d, 0.0))
        px, py = cx - A * d, cy - B * d
        out.append(np.stack([px - B * h, py + A * h], -1))
        out.append(np.stack([px + B * h, py - A * h], -1))
    if nl >= 2:
        i, j = np.triu_indices(nl, 1)
        A1, B1, C1 = L[i, 0], L[i, 1], L[i, 2]
        A2, B2, C2 = L[j, 0], L[j, 1], L[j, 2]
        det = A1 * B2 - A2 * B1
        ok = np.abs(det) > 1e-9
        out.append(np.stack([(C1 * B2 - C2 * B1)[ok] / det[ok], (A1 * C2 - A2 * C1)[ok] / det[ok]], -1))
    if not out: return np.zeros((0, 2))
    return np.vstack(out)


def best_centre(pts, Bl, has_inf, min_deg):
    """Vectorised search for the inversion centre of maximal degree (> min_deg). Returns (deg, O, blocks)."""
    pts = np.asarray(pts, float)
    keys = list(Bl.keys())
    geoms = [precise_geom(pts, Bl[k]) for k in keys]
    C = np.array([[g[1], g[2], g[3]] for g in geoms if g[0] == 'C']).reshape(-1, 3)
    L = np.array([[g[1], g[2], g[3]] for g in geoms if g[0] == 'L']).reshape(-1, 3)
    X = _pair_intersections_vec(C, L)
    if len(X) == 0: return (-1, None, None)
    X = X[np.all(np.isfinite(X), 1)]
    X = X[np.abs(X).max(1) < 1e7]
    # a point on d blocks appears in C(d,2) pairs; need C(d,2) >= C(min_deg+1, 2), and at least 3
    need = max((min_deg + 1) * min_deg // 2, 3)
    reps = []
    for shift in (0.0, 0.5):
        keyarr = np.floor(X / 1e-5 + shift).astype(np.int64)
        u, inv, cnt = np.unique(keyarr, axis=0, return_inverse=True, return_counts=True)
        inv = inv.reshape(-1)
        sel = np.where(cnt >= need)[0]
        if len(sel) == 0: continue
        first = np.zeros(len(u), dtype=np.int64); first[inv[::-1]] = np.arange(len(inv))[::-1]
        reps.append(X[first[sel]])
    if not reps:
        if min_deg >= 2: return (-1, None, None)
        # fall back: any intersection point not in P has degree >= 2
        dP = np.hypot(X[:, None, 0] - pts[None, :, 0], X[:, None, 1] - pts[None, :, 1]).min(1)
        ok = np.where(dP > 1e-5)[0]
        if len(ok) == 0: return (-1, None, None)
        reps.append(X[ok[:1]])
    P = np.vstack(reps)
    if len(P) > 20000: P = P[:20000]
    bestdeg, bestO, bestB = -1, None, None
    if len(C):
        dc = np.abs(np.hypot(P[:, None, 0] - C[None, :, 0], P[:, None, 1] - C[None, :, 1]) - C[None, :, 2]) < OTOL
    else:
        dc = np.zeros((len(P), 0), bool)
    if len(L):
        dl = np.abs(P[:, 0:1] * L[None, :, 0] + P[:, 1:2] * L[None, :, 1] - L[None, :, 2]) < OTOL
    else:
        dl = np.zeros((len(P), 0), bool)
    deg = dc.sum(1) + dl.sum(1)
    # exclude points of P
    dP = np.hypot(P[:, None, 0] - pts[None, :, 0], P[:, None, 1] - pts[None, :, 1]).min(1)
    deg[dP < 1e-5] = -1
    t = int(np.argmax(deg))
    if deg[t] > min_deg:
        O = (float(P[t, 0]), float(P[t, 1]))
        onb = [sorted(Bl[keys[q]]) for q in range(len(keys)) if on_block(geoms[q], O[0], O[1])]
        return (int(deg[t]), O, onb)
    return (-1, None, None)


def evaluate_fast(pts, has_inf=False, want_O=True):
    pts = np.asarray(pts, float)
    n = len(pts)
    if not np.all(np.isfinite(pts)) or np.abs(pts).max() > 1e6: return None
    d2 = ((pts[:, None, :] - pts[None, :, :]) ** 2).sum(-1)
    np.fill_diagonal(d2, 1.0)
    if d2.min() < 1e-12: return None
    Bl = blocks_of(pts, has_inf)
    N = n + (1 if has_inf else 0)
    if any(len(s) == N for s in Bl.values()): return None
    nb = len(Bl)
    nlines = sum(1 for k in Bl if k[0] == 'L')
    sizes = sorted((len(s) for s in Bl.values()), reverse=True)
    res = {'nblocks': nb, 'sizes': sizes, 'lines': nlines, 'euclid': (nb - nlines if not has_inf else None)}
    bestdeg = nlines if not has_inf else -1
    bestO = 'inf' if not has_inf else None
    res['O_blocks'] = None
    if want_O:
        deg, O, onb = best_centre(pts, Bl, has_inf, bestdeg)
        if deg > bestdeg:
            bestdeg, bestO = deg, O; res['O_blocks'] = onb
    res['deg'] = bestdeg; res['O'] = bestO; res['best'] = nb - bestdeg
    return res
