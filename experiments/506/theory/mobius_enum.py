"""Exhaustive enumeration of abstract 'Mobius block structures' for Erdos #506.

Setting.  P = n points of the inversive (Mobius) plane, not all on one circle (circles include
lines).  B(P) = blocks = circles through >= 3 points of P.  Every triple lies in exactly one block,
two blocks share <= 2 points.  Choosing the point 'infinity' (not in P) turns the blocks through it
into straight lines; the Euclidean count is

    circles(P) = |B(P)| - #lines = C(n,3) - D(F) - ell,

where F = family of blocks of size >= 4, D(F) = sum_{B in F} (C(|B|,3) - 1) and ell = number of
lines (blocks through infinity, pairwise meeting in <= 1 point of P).

This module enumerates, up to isomorphism, all pairs (F, L) with count <= target that satisfy the
NECESSARY realisability conditions listed in REPORT.md (Section 3):
  (C1) blocks pairwise share <= 2 points, lines pairwise share <= 1 point, no block of size n;
  (C2) derived Sylvester-Gallai bound at every point p: the blocks through p become lines of a
       non-collinear (n-1)-point set after inversion about p, so the pairs of P\{p} covered by blocks
       of size >= 4 through p number at most C(n-1,2) - o(n-1), o(m) = min # ordinary lines;
  (C3) the same bound at infinity: sum_{l in L} C(|l|,2) <= C(n,2) - o(n).

Families F are generated by Read-Faradzev orderly generation (lexicographically minimal sorted
block list under S_n, tested with a vectorised permutation table), so every isomorphism class of F
appears exactly once.  For each F the line sets L are enumerated by branch and bound.

Usage:  python3 mobius_enum.py n target [outfile.json]
"""
import sys, json, itertools
from math import comb
import numpy as np

# minimum number of ordinary lines of m non-collinear points in the real plane (rigorous lower
# bounds).  m <= 6 elementary; m = 7: Kelly-Moser (3); m >= 8: Csima-Sawyer  o(m) >= 6m/13 (m != 7).
# Exact values 3,3,4,3,3,4 for m = 3..8 are classical; we only use them as LOWER bounds.
def o_lower(m):
    if m <= 2:
        return 0
    exact = {3: 3, 4: 3, 5: 4, 6: 3, 7: 3, 8: 4}
    if m in exact:
        return exact[m]
    return max(-(-3 * m // 7), -(-6 * m // 13))  # ceil(3m/7), ceil(6m/13)


def popcount(x):
    return bin(x).count("1")


class Enumerator:
    def __init__(self, n, target, min_block=4, verbose=True):
        self.n = n
        self.target = target
        self.verbose = verbose
        self.N3 = comb(n, 3)
        self.cap_derived = comb(n - 1, 2) - o_lower(n - 1)   # (C2)
        self.cap_lines = comb(n, 2) - o_lower(n)              # (C3)
        # ell is at most cap_lines/3 (each line covers >= 3 pairs)
        self.ell_max = self.cap_lines // 3
        self.D_min = self.N3 - target - self.ell_max
        # candidate blocks: subsets of size min_block..n-1 as bitmasks, ordered by code
        self.cands = [c for c in range(1 << n) if min_block <= popcount(c) <= n - 1]
        self.size = {c: popcount(c) for c in self.cands}
        self.deficit = {c: comb(self.size[c], 3) - 1 for c in self.cands}
        # permutation table for canonicity: PI[perm, code] = image code
        perms = list(itertools.permutations(range(n)))
        self.P = len(perms)
        codes = np.arange(1 << n, dtype=np.int64)
        bits = ((codes[:, None] >> np.arange(n)) & 1).astype(np.int64)      # (2^n, n)
        pow_perm = np.zeros((n, self.P), dtype=np.int64)
        for j, s in enumerate(perms):
            for i in range(n):
                pow_perm[i, j] = 1 << s[i]
        self.PI = (bits @ pow_perm).T.astype(np.int32)                         # (P, 2^n)
        self.results = []
        self.nodes = 0

    # ---- canonicity (orderly generation) ------------------------------------------------
    def is_canonical(self, F):
        Fs = np.array(sorted(F), dtype=np.int32)
        M = np.sort(self.PI[:, Fs], axis=1)
        alive = np.ones(self.P, dtype=bool)
        for j in range(len(Fs)):
            col = M[:, j]
            if np.any(alive & (col < Fs[j])):
                return False
            alive &= (col == Fs[j])
        return True

    # ---- coverage bookkeeping for (C2) --------------------------------------------------
    def cov_add(self, cov, b, sign=1):
        k = self.size[b]
        inc = comb(k - 1, 2) * sign
        for p in range(self.n):
            if b >> p & 1:
                cov[p] += inc

    def compatible(self, F, b):
        for a in F:
            if popcount(a & b) > 2:
                return False
        return True

    # ---- main DFS -----------------------------------------------------------------------
    def run(self):
        cov = [0] * self.n
        self.dfs([], -1, cov, 0)
        return self.results

    def dfs(self, F, last, cov, D):
        self.nodes += 1
        if D >= self.D_min:
            self.process(F, D)
        # potential: remaining coverage budget / 3 bounds the extra deficit (each block of size k
        # consumes k*C(k-1,2) = 3*C(k,3) units of budget for deficit C(k,3)-1 < C(k,3)).
        budget = sum(self.cap_derived - c for c in cov)
        if D + budget // 3 < self.D_min:
            return
        # candidate list for extension (codes > last, compatible)
        ext = []
        for b in self.cands:
            if b <= last:
                continue
            if not self.compatible(F, b):
                continue
            k = self.size[b]
            inc = comb(k - 1, 2)
            if any(cov[p] + inc > self.cap_derived for p in range(self.n) if b >> p & 1):
                continue
            ext.append(b)
        if D + sum(self.deficit[b] for b in ext) < self.D_min:
            return
        for idx, b in enumerate(ext):
            # cheaper potential bound using only later candidates
            rest = sum(self.deficit[c] for c in ext[idx:])
            if D + rest < self.D_min:
                break
            F2 = F + [b]
            if not self.is_canonical(F2):
                continue
            self.cov_add(cov, b, 1)
            self.dfs(F2, b, cov, D + self.deficit[b])
            self.cov_add(cov, b, -1)

    # ---- line sets ----------------------------------------------------------------------
    def uncovered_triples(self, F):
        n = self.n
        out = []
        for t in itertools.combinations(range(n), 3):
            code = sum(1 << i for i in t)
            if not any(code & b == code for b in F):
                out.append(code)
        return out

    def line_sets(self, F, need):
        """All sets L (as lists of codes) of pairwise <=1-intersecting blocks (from F and the
        uncovered triples) with |L| >= need and pair-coverage <= cap_lines.  Returns list of
        maximal such sets with |L| >= need (each candidate set of size >= need is contained in a
        maximal one; we report maximal ones and the maximum size)."""
        cands = sorted(F) + self.uncovered_triples(F)
        m = len(cands)
        pairs = [comb(popcount(c), 2) for c in cands]
        adj = [[popcount(cands[i] & cands[j]) <= 1 for j in range(m)] for i in range(m)]
        best = [0]
        found = []

        def rec(start, chosen, used_pairs):
            # bound: remaining candidates that are compatible with all chosen
            avail = [j for j in range(start, m) if all(adj[i][j] for i in chosen)]
            if len(chosen) + len(avail) < need:
                return
            extended = False
            for j in avail:
                if used_pairs + pairs[j] > self.cap_lines:
                    continue
                extended = True
                rec(j + 1, chosen + [j], used_pairs + pairs[j])
            if not extended and len(chosen) >= need:
                # maximal w.r.t. later candidates; check global maximality
                if all(not all(adj[i][j] for i in chosen) or used_pairs + pairs[j] > self.cap_lines
                       for j in range(m) if j not in chosen):
                    found.append([cands[i] for i in chosen])
                    best[0] = max(best[0], len(chosen))

        rec(0, [], 0)
        return best[0], found

    def process(self, F, D):
        need = self.N3 - self.target - D     # lines needed to reach count <= target
        need = max(need, 0)
        ell, sets = self.line_sets(F, need)
        if ell < need:
            return
        count = self.N3 - D - ell
        rec = {"n": self.n, "blocks": [sorted(self.decode(b)) for b in sorted(F)],
               "sizes": sorted([self.size[b] for b in F], reverse=True), "D": D,
               "ell_max": ell, "count_min": count,
               "degrees": [sum(1 for b in F if b >> p & 1) for p in range(self.n)],
               "line_sets": [[sorted(self.decode(l)) for l in L] for L in sets]}
        self.results.append(rec)
        if self.verbose:
            print(f"  candidate: sizes={rec['sizes']} D={D} ell_max={ell} count={count} "
                  f"degrees={rec['degrees']} #line-sets={len(sets)}", flush=True)

    def decode(self, code):
        return [i for i in range(self.n) if code >> i & 1]


def main():
    n = int(sys.argv[1]); target = int(sys.argv[2])
    out = sys.argv[3] if len(sys.argv) > 3 else None
    E = Enumerator(n, target)
    print(f"n={n} target={target}: C(n,3)={E.N3}, cap_derived={E.cap_derived}, cap_lines={E.cap_lines}, "
          f"ell_max={E.ell_max}, D_min={E.D_min}", flush=True)
    res = E.run()
    print(f"nodes visited: {E.nodes}; candidate structures with count <= {target}: {len(res)}")
    if out:
        with open(out, "w") as f:
            json.dump(res, f, indent=1)


if __name__ == "__main__":
    main()
