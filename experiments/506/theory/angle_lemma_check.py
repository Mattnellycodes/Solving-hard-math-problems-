"""Algebraic cross-check of the Angle Lemma (REPORT.md, Lemma 2.3):
four lines in general position (complete quadrilateral, vertices P_ij = L_i ∩ L_j) cannot have all
three 'diagonal quadruples' {P12,P34,P13,P24}, {P12,P34,P14,P23}, {P13,P24,P14,P23} concyclic.
We use slopes m_i (lines y = m_i x + c_i, no line vertical WLOG after a rotation) and the exact
concyclicity determinant; then show the ideal generated by the three concyclicity polynomials,
saturated by the products of slope differences (non-parallel) and by the 'vertices distinct'
conditions, is the unit ideal.  We do it with a Groebner basis over QQ in sympy, after using the
affine freedom to fix L1: y = 0 (m1 = 0, c1 = 0) and L2 through the origin (c2 = 0)."""
import sympy as sp
m2, m3, m4, c3, c4, t = sp.symbols('m2 m3 m4 c3 c4 t')
m1 = 0; c1 = 0; c2 = 0
L = {1: (m1, c1), 2: (m2, c2), 3: (m3, c3), 4: (m4, c4)}
def inter(i, j):
    mi, ci = L[i]; mj, cj = L[j]
    x = (cj - ci) / (mi - mj); y = mi * x + ci
    return sp.simplify(x), sp.simplify(y)
P = {(i, j): inter(i, j) for i, j in [(1,2),(1,3),(1,4),(2,3),(2,4),(3,4)]}
def concyc(a, b, c, d):
    rows = [[x, y, x*x + y*y, 1] for (x, y) in (a, b, c, d)]
    return sp.together(sp.Matrix(rows).det())
Q1 = concyc(P[(1,2)], P[(3,4)], P[(1,3)], P[(2,4)])
Q2 = concyc(P[(1,2)], P[(3,4)], P[(1,4)], P[(2,3)])
Q3 = concyc(P[(1,3)], P[(2,4)], P[(1,4)], P[(2,3)])
nums = [sp.factor(sp.numer(sp.together(Q))) for Q in (Q1, Q2, Q3)]
print("numerators (factored):")
for q in nums: print("  ", q)
# non-degeneracy: slopes pairwise distinct (non-parallel), and c3, c4 != 0, c3 != c4 ... vertices distinct.
# Rabinowitsch: t * (product of all these) - 1
nd = (m2)*(m3)*(m4)*(m2-m3)*(m2-m4)*(m3-m4)*c3*c4*(c3-c4)*(m2*c4 - m4*c3)*(m2*c3-m3*c2 if False else 1)
# vertices distinct conditions: P12=(0,0); P13=(-c3/m3,0); P14=(-c4/m4,0); P23=(c3/(m2-m3),..); P24; P34
# distinctness of all six vertices amounts to: c3!=0, c4!=0, c3*m4 != c4*m3 (P13!=P14), P23!=P24: c3/(m2-m3)!=c4/(m2-m4),
# P34 != others ... include the ones that matter:
nd = nd * (c3*(m2-m4) - c4*(m2-m3)) * (c3*m4 - c4*m3)
G = sp.groebner([sp.expand(q) for q in nums] + [t*nd - 1], m2, m3, m4, c3, c4, t, order='grevlex')
print("Groebner basis of (Q1,Q2,Q3) saturated by non-degeneracy:", list(G))
print("UNIT IDEAL (no complex, hence no real, solutions):", list(G) == [1])
# Also demonstrate that two of the three conditions force perpendicularity: add Q1,Q2 only
G2 = sp.groebner([sp.expand(nums[0]), sp.expand(nums[1]), t*nd - 1], m2, m3, m4, c3, c4, t, order='lex')
print("Q1,Q2 only, lex basis:")
for g in G2: print("  ", sp.factor(g))
