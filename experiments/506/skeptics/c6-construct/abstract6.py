"""From-scratch enumeration of abstract Moebius block structures on 6 points with
C(6,3) - D - l <= TARGET, using ONLY the two intersection axioms
(blocks share <= 2 points, lines share <= 1 point).  No Sylvester-Gallai, no Angle Lemma.
Outputs every (F, L) up to isomorphism (canonical form by brute force over S_6).
"""
import sys, json
from itertools import combinations, permutations
from math import comb

N = 6
TARGET = int(sys.argv[1]) if len(sys.argv) > 1 else 7
PTS = range(N)
subsets45 = [frozenset(s) for k in (4, 5) for s in combinations(PTS, k)]
triples = [frozenset(t) for t in combinations(PTS, 3)]
PERMS = list(permutations(PTS))


def canon(F, L):
    best = None
    for p in PERMS:
        key = (tuple(sorted(tuple(sorted(p[i] for i in b)) for b in F)),
               tuple(sorted(tuple(sorted(p[i] for i in b)) for b in L)))
        if best is None or key < best:
            best = key
    return best


def families(start, F):
    """All families of 4/5-subsets pairwise sharing <= 2 points (as sets, generated by index order)."""
    yield F
    for idx in range(start, len(subsets45)):
        b = subsets45[idx]
        if all(len(b & x) <= 2 for x in F):
            yield from families(idx + 1, F + [b])


results = {}
nF = 0
for F in families(0, []):
    nF += 1
    D = sum(comb(len(b), 3) - 1 for b in F)
    covered = {t for b in F for t in triples if t <= b}
    blocks = list(F) + [t for t in triples if t not in covered]
    assert len(blocks) == comb(N, 3) - D
    need_l = comb(N, 3) - D - TARGET   # need l >= need_l
    if need_l > len(blocks):
        continue
    # enumerate all line sets (subsets of blocks pairwise sharing <= 1 point) of size >= need_l
    def linesets(start, L):
        if len(L) >= need_l:
            yield list(L)
        for i in range(start, len(blocks)):
            b = blocks[i]
            if all(len(b & x) <= 1 for x in L):
                yield from linesets(i + 1, L + [b])
    for L in linesets(0, []):
        cnt = comb(N, 3) - D - len(L)
        key = canon(F, L)
        if key not in results:
            results[key] = cnt
print(f"families of 4/5-blocks visited: {nF}")
print(f"non-isomorphic (F, L) with count <= {TARGET}: {len(results)}")
out = []
for key, cnt in sorted(results.items(), key=lambda kv: kv[1]):
    F, L = key
    print(f"count={cnt}  D={comb(N,3)-cnt-len(L)}  blocks>=4: {list(map(list, F))}  lines: {list(map(list, L))}")
    out.append({"count": cnt, "F": [list(b) for b in F], "L": [list(b) for b in L]})
json.dump(out, open(f"abstract6_t{TARGET}.json", "w"), indent=1)
