"""Independent audit of the Angle Lemma (REPORT Lemma 2.3): four lines, pairwise non-parallel, no three
concurrent; vertices P_ij.  Claim: the three diagonal quadruples {P12,P34,P13,P24}, {P12,P34,P14,P23},
{P13,P24,P14,P23} are never all concyclic.
Method: a similarity puts L1 on y=0 with P12 at the origin (concyclicity is similarity-invariant).
Each of L2, L3, L4 is then either vertical (x = d) or non-vertical (y = m x + c); L2 passes through the
origin.  All 8 charts are treated; in each, the ideal generated by the three concyclicity determinants,
saturated (Rabinowitsch) by EXACTLY the non-degeneracy hypotheses (pairwise non-parallel, no three
concurrent), is shown to be the unit ideal.  Also: which PAIRS of the three conditions are jointly
satisfiable (the report's proof says two conditions already force perpendicular lines)."""
import itertools, sympy as sp
m2, m3, m4, c3, c4, d2, d3, d4, t = sp.symbols('m2 m3 m4 c3 c4 d2 d3 d4 t')

def line(kind, i):
    # returns (a, b, c) with a x + b y + c = 0
    if i == 1: return (0, 1, 0)                       # y = 0
    if i == 2: return (1, 0, 0) if kind == 'v' else (m2, -1, 0)      # x = 0 or y = m2 x
    m, c, d = {3: (m3, c3, d3), 4: (m4, c4, d4)}[i]
    return (1, 0, -d) if kind == 'v' else (m, -1, c)

def meet(L, M):
    a1, b1, c1 = L; a2, b2, c2 = M
    det = a1 * b2 - a2 * b1
    return (sp.together((b1 * c2 - b2 * c1) / det), sp.together((c1 * a2 - c2 * a1) / det))

def concyc(pts):
    return sp.Matrix([[x * x + y * y, x, y, 1] for x, y in pts]).det()

total_ok = True
for kinds in itertools.product('nv', repeat=3):
    if kinds.count('v') >= 2:      # two vertical lines are parallel: excluded by hypothesis
        continue
    Ls = {1: line('n', 1), 2: line(kinds[0], 2), 3: line(kinds[1], 3), 4: line(kinds[2], 4)}
    nondeg = []
    for i, j in itertools.combinations(range(1, 5), 2):          # pairwise non-parallel
        a1, b1, _ = Ls[i]; a2, b2, _ = Ls[j]
        nondeg.append(a1 * b2 - a2 * b1)
    for i, j, k in itertools.combinations(range(1, 5), 3):       # no three concurrent
        nondeg.append(sp.Matrix([Ls[i], Ls[j], Ls[k]]).det())
    nondeg = [sp.expand(e) for e in nondeg]
    if any(e == 0 for e in nondeg):
        print(kinds, "chart degenerate identically (skipped)"); continue
    P = {(i, j): meet(Ls[i], Ls[j]) for i, j in itertools.combinations(range(1, 5), 2)}
    Q = [concyc([P[(1, 2)], P[(3, 4)], P[(1, 3)], P[(2, 4)]]),
         concyc([P[(1, 2)], P[(3, 4)], P[(1, 4)], P[(2, 3)]]),
         concyc([P[(1, 3)], P[(2, 4)], P[(1, 4)], P[(2, 3)]])]
    Q = [sp.factor(sp.numer(sp.together(q))) for q in Q]
    syms = sorted(set().union(*[q.free_symbols for q in Q] + [e.free_symbols for e in nondeg]), key=str)
    prod = sp.Mul(*[sp.factor(e) for e in nondeg])
    G = sp.groebner([sp.expand(q) for q in Q] + [sp.expand(t * prod - 1)], *syms, t, order='grevlex')
    unit = list(G) == [1]
    total_ok &= unit
    pairs = []
    for a, b in itertools.combinations(range(3), 2):
        Gp = sp.groebner([sp.expand(Q[a]), sp.expand(Q[b]), sp.expand(t * prod - 1)], *syms, t, order='grevlex')
        pairs.append(list(Gp) == [1])
    print(f"chart (L2,L3,L4)={kinds}: all three concyclic + nondegenerate => unit ideal: {unit}; "
          f"pairs (0,1),(0,2),(1,2) infeasible: {pairs}")
print("ANGLE LEMMA holds in every chart:", total_ok)
