"""Construction attack via 'closure pools' + local search.
Pools of points with many forced concyclicities/collinearities are generated by intersecting blocks
(lines through 2 pool points, circles through 3 pool points) of a random rational seed; then a
simulated-annealing search over 9-subsets minimises the float circle count (tolerance-clustered).
Also, for every candidate 9-set, the Mobius trick is applied: count after the best inversion
= |B| - (max number of blocks concurrent at a non-configuration point).  Any 9-set with count <= 24
would be printed for exact verification."""
import numpy as np, itertools, math, sys, time, random
from fractions import Fraction as Fr
TOL = 1e-8
TRIPLES = np.array(list(itertools.combinations(range(9), 3)))

def block_vectors(P):
    """P: (9,2) float array -> normalised (A,B,C,D) vectors of circle/line through each triple."""
    X = P[TRIPLES]                              # (84,3,2)
    w = X[..., 0] ** 2 + X[..., 1] ** 2         # (84,3)
    M = np.stack([w, X[..., 0], X[..., 1], np.ones_like(w)], axis=-1)   # (84,3,4)
    # cofactor vector orthogonal to the 3 rows
    def minor(cols):
        return np.linalg.det(M[:, :, cols])
    v = np.stack([minor([1, 2, 3]), -minor([0, 2, 3]), minor([0, 1, 3]), -minor([0, 1, 2])], axis=-1)
    nrm = np.linalg.norm(v, axis=1, keepdims=True)
    v = v / np.where(nrm < 1e-14, 1, nrm)
    # sign normalisation: first nonzero component positive
    for k in range(4):
        s = np.sign(v[:, k]); s[np.abs(v[:, k]) < 1e-7] = 0
        v = v * np.where((s != 0)[:, None], s[:, None], 1)
        # once component k is nonzero for a row, later k must not flip it: handle by marking done
        done = np.abs(v[:, k]) > 1e-7
        if k == 0: mask = done
        else:
            v[mask] = v[mask]  # unchanged
            mask = mask | done
    return v, nrm[:, 0]

def count_circles(P):
    """returns (circles, lines, degenerate) for 9 float points."""
    v, nrm = block_vectors(P)
    if np.any(nrm < 1e-12): return None
    # cluster by rounding (robust enough for pools derived from rational seeds)
    keys = {}
    for i in range(84):
        k = tuple(np.round(v[i] / 1e-6).astype(np.int64))
        keys.setdefault(k, set()).update(TRIPLES[i].tolist())
    if any(len(s) == 9 for s in keys.values()): return None
    circles = sum(1 for k in keys if abs(k[0]) > 0)
    lines = len(keys) - circles
    return circles, lines, keys

def rand_rational(lo=-4, hi=4, den=4):
    return Fr(random.randint(lo * den, hi * den), den)

def seed_pool(nseed, nmax, rng_seed):
    random.seed(rng_seed)
    pts = []
    while len(pts) < nseed:
        p = (rand_rational(), rand_rational())
        if p not in pts: pts.append(p)
    P = [(float(x), float(y)) for x, y in pts]
    # blocks: lines through pairs, circles through triples
    lines = set(); circles = set()
    for a, b in itertools.combinations(pts, 2):
        A = b[1] - a[1]; B = a[0] - b[0]; C = A * a[0] + B * a[1]
        lines.add((A, B, C))
    for a, b, c in itertools.combinations(pts, 3):
        (x1, y1), (x2, y2), (x3, y3) = a, b, c
        d = 2 * (x1 * (y2 - y3) + x2 * (y3 - y1) + x3 * (y1 - y2))
        if d == 0: continue
        s1 = x1 * x1 + y1 * y1; s2 = x2 * x2 + y2 * y2; s3 = x3 * x3 + y3 * y3
        ux = (s1 * (y2 - y3) + s2 * (y3 - y1) + s3 * (y1 - y2)) / d
        uy = (s1 * (x3 - x2) + s2 * (x1 - x3) + s3 * (x2 - x1)) / d
        circles.add((ux, uy, (x1 - ux) ** 2 + (y1 - uy) ** 2))
    lines = list(lines); circles = list(circles)
    random.shuffle(lines); random.shuffle(circles)
    pool = list(P)
    def add(q):
        if any(abs(q[0] - x) < 1e-9 and abs(q[1] - y) < 1e-9 for x, y in pool): return
        if abs(q[0]) > 50 or abs(q[1]) > 50: return
        pool.append(q)
    # line-line
    for (A1, B1, C1), (A2, B2, C2) in itertools.combinations(lines, 2):
        det = A1 * B2 - A2 * B1
        if det == 0: continue
        add((float((C1 * B2 - C2 * B1) / det), float((A1 * C2 - A2 * C1) / det)))
        if len(pool) >= nmax: return pool
    # line-circle
    for (A, B, C) in lines:
        for (ux, uy, r2) in circles:
            A, B, C, ux, uy, r2 = map(float, (A, B, C, ux, uy, r2))
            n = math.hypot(A, B); nx, ny = A / n, B / n; d = C / n
            t = d - (nx * ux + ny * uy); h2 = r2 - t * t
            if h2 <= 1e-12: continue
            h = math.sqrt(h2); fx, fy = ux + t * nx, uy + t * ny
            add((fx - h * ny, fy + h * nx)); add((fx + h * ny, fy - h * nx))
            if len(pool) >= nmax: return pool
    # circle-circle
    for (x1, y1, r1s), (x2, y2, r2s) in itertools.combinations(circles, 2):
        x1, y1, r1s, x2, y2, r2s = map(float, (x1, y1, r1s, x2, y2, r2s))
        r1, r2 = math.sqrt(r1s), math.sqrt(r2s)
        dd = math.hypot(x2 - x1, y2 - y1)
        if dd < 1e-12 or dd > r1 + r2 - 1e-9 or dd < abs(r1 - r2) + 1e-9: continue
        a = (r1 * r1 - r2 * r2 + dd * dd) / (2 * dd); h = math.sqrt(max(r1 * r1 - a * a, 0))
        mx, my = x1 + a * (x2 - x1) / dd, y1 + a * (y2 - y1) / dd
        add((mx - h * (y2 - y1) / dd, my + h * (x2 - x1) / dd)); add((mx + h * (y2 - y1) / dd, my - h * (x2 - x1) / dd))
        if len(pool) >= nmax: return pool
    return pool

def circle_pool(k):
    """rational points on the unit circle (k of them, antipodal-closed) + centre + chord intersections."""
    pts = [(Fr(0), Fr(0))]
    t = 1
    while len(pts) < k + 1:
        x = Fr(1 - t * t, 1 + t * t); y = Fr(2 * t, 1 + t * t)
        for p in [(x, y), (-x, -y), (x, -y), (-x, y)]:
            if p not in pts and len(pts) < k + 1: pts.append(p)
        t += 1
    onc = pts[1:]
    pool = [(float(x), float(y)) for x, y in pts]
    for (a, b), (c, d) in itertools.combinations(itertools.combinations(onc, 2), 2):
        if len({a, b, c, d}) < 4: continue
        A1 = b[1] - a[1]; B1 = a[0] - b[0]; C1 = A1 * a[0] + B1 * a[1]
        A2 = d[1] - c[1]; B2 = c[0] - d[0]; C2 = A2 * c[0] + B2 * c[1]
        det = A1 * B2 - A2 * B1
        if det == 0: continue
        q = (float((C1 * B2 - C2 * B1) / det), float((A1 * C2 - A2 * C1) / det))
        if abs(q[0]) < 3 and abs(q[1]) < 3 and not any(abs(q[0] - x) < 1e-9 and abs(q[1] - y) < 1e-9 for x, y in pool):
            pool.append(q)
    return pool

def sa_search(pool, iters, rng_seed, T0=1.5):
    random.seed(rng_seed)
    pool = np.array(pool); m = len(pool)
    def score(S):
        r = count_circles(pool[list(S)])
        return 999 if r is None else r[0]
    while True:
        S = set(random.sample(range(m), 9)); sc = score(S)
        if sc < 999: break
    best = (sc, sorted(S))
    for it in range(iters):
        T = T0 * (1 - it / iters) + 0.05
        out = random.choice(sorted(S)); inn = random.randrange(m)
        if inn in S: continue
        S2 = (S - {out}) | {inn}; sc2 = score(S2)
        if sc2 <= sc or random.random() < math.exp((sc - sc2) / T):
            S, sc = S2, sc2
            if sc < best[0]: best = (sc, sorted(S))
    return best

if __name__ == "__main__":
    mode = sys.argv[1]; budget = float(sys.argv[2])
    t0 = time.time(); overall = (999, None, None)
    runs = 0
    while time.time() - t0 < budget:
        runs += 1
        if mode == "closure":
            pool = seed_pool(nseed=random.choice([4, 5, 5, 6]), nmax=random.choice([30, 45, 60]), rng_seed=runs)
        elif mode == "circle":
            pool = circle_pool(random.choice([8, 12, 16]))
        else:
            raise SystemExit("mode closure|circle")
        sc, S = sa_search(pool, iters=4000, rng_seed=1000 + runs)
        pts = [pool[i] for i in S]
        if sc < overall[0]:
            overall = (sc, pts, runs)
            print(f"run {runs} pool={len(pool)}: new best circles={sc} pts={[(round(x,6),round(y,6)) for x,y in pts]}", flush=True)
        if sc <= 24:
            print("!!! candidate with <= 24 circles:", pts, flush=True)
    print(f"{mode}: runs={runs} best circle count={overall[0]}")
