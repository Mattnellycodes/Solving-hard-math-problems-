"""Case A (a 6-block) is impossible: geometric argument + algebraic certificate.

Structure (forced by counting, confirmed by the CP-SAT enumeration): a 6-block S6 (a circle C on the
sphere), its complement R = {r6,r7,r8,r9} a block, and for every pair {r,r'} of R and every a in S6 the
triple {a,r,r'} lies in a 4-block {a,b,r,r'} with b in S6.  Hence:
 (1) each pair {r,r'} induces a fixed-point-free perfect matching M_{rr'} of S6 which is the restriction
     of the projective involution of C cut out by the pencil of circles through r,r' (Frégier
     involution with centre X_{rr'} = line(rr') ∩ plane(C) on the sphere);
 (2) two pairs sharing a point of R have edge-disjoint matchings (else two 4-blocks share 3 points);
 (3) the group G generated by the six involutions preserves S6, hence is finite (faithful on S6), hence
     conjugate into O(2): S6 is a union of regular m-gons (m | 6) and the usable involutions are the
     half-turn and the reflections whose axes avoid S6.  Case analysis (m = 1,2,3,6) shows: at most
     three pairwise edge-disjoint usable involutions exist and every 'star' {rr',rr'',rr'''} uses all of
     them, so complementary pairs get the same involution: X_{67}=X_{89}, X_{68}=X_{79}, X_{69}=X_{78};
 (4) then lines r6r7 and r8r9 meet, so R is coplanar and its three diagonal points X_{67},X_{68},X_{69}
     lie on the line plane(R) ∩ plane(C) — but the diagonal points of a complete quadrangle in RP²
     are never collinear.  Contradiction.
This script certifies the algebraic core of (3): with t0=0, t1=1, t2=∞, t3=a, t4=b, t5=c on the conic,
for every choice of matchings I1,I2,I3 pairwise disjoint and I4 ≠ I1 disjoint from I2,I3, the four
involution conditions have no real solution with six distinct points.  (If complementary matchings
differ, star 8 and star 9 force M_{89} to be such an I4.)
"""
import itertools, sympy as sp

a, b, c = sp.symbols('a b c')
PTS = {0: (0, 1), 1: (1, 1), 2: (1, 0), 3: (a, 1), 4: (b, 1), 5: (c, 1)}   # homogeneous (x:y)


def inv_condition(matching):
    rows = []
    for (i, j) in matching:
        xi, yi = PTS[i]; xj, yj = PTS[j]
        rows.append([xi * xj, xi * yj + xj * yi, yi * yj])
    return sp.expand(sp.Matrix(rows).det())


def perfect_matchings():
    out = []
    def rec(rem, cur):
        if not rem:
            out.append(frozenset(cur)); return
        i = rem[0]
        for j in rem[1:]:
            rec([k for k in rem if k not in (i, j)], cur + [(i, j)])
    rec(list(range(6)), [])
    return out


PM = perfect_matchings()
assert len(PM) == 15
disjoint = lambda M1, M2: not (M1 & M2)
nondeg = [a, b, c, a - 1, b - 1, c - 1, a - b, a - c, b - c]


def real_solutions(eqs):
    """Real solutions (a,b,c) with all nondegeneracy conditions, via Groebner basis + solve."""
    G = sp.groebner(eqs, a, b, c, order='lex')
    if list(G) == [1]:
        return [], 'unit ideal'
    sols = sp.solve(list(G), [a, b, c], dict=True)
    good = []
    for s in sols:
        if len(s) < 3:
            return None, f'positive-dimensional: {s}'
        vals = [sp.nsimplify(s[v]) for v in (a, b, c)]
        if all(sp.im(sp.N(v)) == 0 for v in vals) and all(sp.N(nd.subs(s)) != 0 for nd in nondeg):
            good.append(s)
    return good, 'ok'


if __name__ == '__main__':
    # sanity: the regular hexagon has exactly the 4 involutive matchings claimed.
    # regular hexagon on the conic: choose the parametrisation t = tan(theta/2) of the unit circle
    hexa = {i: sp.tan(sp.pi * i / 6) for i in range(6)}   # theta = 60 i degrees, t = tan(theta/2)
    def inv_num(matching):
        rows = []
        for (i, j) in matching:
            ti, tj = hexa[i], hexa[j]
            if ti == sp.zoo or tj == sp.zoo:   # t = infinity for theta = 180
                # use homogeneous coords (1:0)
                xi, yi = (1, 0) if ti == sp.zoo else (ti, 1)
                xj, yj = (1, 0) if tj == sp.zoo else (tj, 1)
            else:
                xi, yi, xj, yj = ti, 1, tj, 1
            rows.append([xi * xj, xi * yj + xj * yi, yi * yj])
        return sp.simplify(sp.Matrix(rows).det())
    inv_hex = [M for M in PM if inv_num(M) == 0]
    print("regular hexagon: involutive perfect matchings:", [sorted(M) for M in inv_hex])
    # main certificate
    checked = 0; bad = []
    seen = set()
    for I1, I2, I3 in itertools.combinations(PM, 3):
        if not (disjoint(I1, I2) and disjoint(I1, I3) and disjoint(I2, I3)):
            continue
        for I4 in PM:
            if I4 in (I1, I2, I3) or not (disjoint(I4, I2) and disjoint(I4, I3)):
                continue
            key = frozenset([I1, I4]) , frozenset([I2, I3])
            if key in seen:
                continue
            seen.add(key)
            eqs = [inv_condition(sorted(M)) for M in (I1, I2, I3, I4)]
            sols, status = real_solutions(eqs)
            checked += 1
            print(f"I1={sorted(I1)} I2={sorted(I2)} I3={sorted(I3)} I4={sorted(I4)}: {status}, real nondegenerate solutions: {sols}")
            if sols is None or sols:
                bad.append((I1, I2, I3, I4, sols, status))
    print(f"checked {checked} configurations; failures: {len(bad)}")
