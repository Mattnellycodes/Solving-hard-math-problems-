"""Own check of the cross-ratio identity behind Miquel's theorem.  For 8 points z_v (v in {0,1}^3)
and each face, with vertices (a,b,c,d) in cyclic order, the six cross-ratio values of the face are
generated by lam = (a-c)(b-d)/((a-d)(b-c)) under lam -> 1/lam, 1-lam.  We find (numerically, then
verify symbolically) a choice of one value per face whose product is identically 1.  Since the
six values of a face are all real or all non-real (points distinct), five concyclic faces force
the sixth to be concyclic."""
import sympy as sp
import random
from itertools import product

z = {v: sp.Symbol("z" + "".join(map(str, v))) for v in product((0, 1), repeat=3)}


def face(axis, val):
    others = [i for i in range(3) if i != axis]
    order = [(0, 0), (1, 0), (1, 1), (0, 1)]
    vs = []
    for o in order:
        v = [0, 0, 0]
        v[axis] = val
        v[others[0]], v[others[1]] = o
        vs.append(tuple(v))
    return vs


faces = [face(ax, val) for ax in range(3) for val in (0, 1)]
variants = [lambda l: l, lambda l: 1 / l, lambda l: 1 - l, lambda l: 1 / (1 - l), lambda l: (l - 1) / l, lambda l: l / (l - 1)]


def lam(a, b, c, d):
    return (a - c) * (b - d) / ((a - d) * (b - c))


random.seed(3)
num = {s: complex(random.uniform(-3, 3), random.uniform(-3, 3)) for s in z.values()}
lams = [lam(*(num[z[v]] for v in f)) for f in faces]
hits = []
for choice in product(range(6), repeat=6):
    p = 1
    for l, c in zip(lams, choice):
        p *= variants[c](l)
    if abs(p - 1) < 1e-9:
        hits.append(choice)
print("numeric hits:", len(hits), hits[:5])
ok = None
for choice in hits:
    p = 1
    for f, c in zip(faces, choice):
        p *= variants[c](lam(*(z[v] for v in f)))
    if sp.cancel(p) == 1:
        ok = choice
        break
print("symbolically verified choice:", ok)
assert ok is not None
print("Miquel cross-ratio identity verified: product of the six face cross ratios == 1 identically")
