"""Exact certification of records found by run_all.py / family_scan.py.

Two exact routes:
 (a) planar universes with exact (rational / radical) coordinates: the inversion centre O is
     recovered exactly as an intersection point of two blocks through it (sympy), and the inverted
     set is counted with exact_verify.certify in the algebraic field generated by the coordinates;
 (b) lattice-sphere universes: the projection centre Q is recovered exactly as an intersection of two
     integer block planes with the sphere x^2+y^2+z^2 = N (coordinates in Q(sqrt(disc))), and the
     circle count is the number of integer planes through >= 3 points of S minus those through Q,
     evaluated with exact quadratic-field arithmetic (lattice_sphere.planes_exact).
"""
import sys, json, math, itertools
from fractions import Fraction as Fr
import numpy as np
import sympy as sp
import sphere as SP
import lattice_sphere as LS
from exact_verify import certify, count_circles_exact, make_field, conv


# ---------------------------------------------------------------- quadratic field elements
class QF:
    """a + b*sqrt(d) with Fractions (d a fixed square-free integer, or d == 1 for rationals)."""
    __slots__ = ('a', 'b', 'd')
    def __init__(self, a, b=0, d=1):
        self.a = Fr(a); self.b = Fr(b); self.d = d
    def __add__(self, o):
        o = o if isinstance(o, QF) else QF(o, 0, self.d)
        return QF(self.a + o.a, self.b + o.b, self.d)
    __radd__ = __add__
    def __sub__(self, o):
        o = o if isinstance(o, QF) else QF(o, 0, self.d)
        return QF(self.a - o.a, self.b - o.b, self.d)
    def __rsub__(self, o):
        return QF(o, 0, self.d) - self
    def __mul__(self, o):
        o = o if isinstance(o, QF) else QF(o, 0, self.d)
        return QF(self.a * o.a + self.b * o.b * self.d, self.a * o.b + self.b * o.a, self.d)
    __rmul__ = __mul__
    def __neg__(self):
        return QF(-self.a, -self.b, self.d)
    def is_zero(self):
        return self.a == 0 and self.b == 0
    def __float__(self):
        return float(self.a) + float(self.b) * math.sqrt(self.d)
    def __repr__(self):
        return f"({self.a} + {self.b}*sqrt({self.d}))"


def _squarefree(n):
    n = int(n); s = 1
    if n < 0:
        s = -1; n = -n
    f = 2; core = 1
    while f * f <= n:
        c = 0
        while n % f == 0:
            n //= f; c += 1
        if c % 2:
            core *= f
        f += 1
    return s * core * n


def exact_sphere_centre(planes, k1, k2, N, target):
    """Exact intersection points of integer planes k1, k2 with the sphere |x|^2 = N; returns the one
    closest to the float target as a triple of QF (coordinates scaled so that the point is on the
    sphere of radius sqrt(N), i.e. matching the integer lattice points)."""
    a1, b1, c1, d1 = k1; a2, b2, c2, d2 = k2
    # direction u = n1 x n2 (integers); a point p0 on the line (rational): solve with two of the coords
    n1 = np.array([a1, b1, c1], dtype=object); n2 = np.array([a2, b2, c2], dtype=object)
    u = (Fr(b1 * c2 - c1 * b2), Fr(c1 * a2 - a1 * c2), Fr(a1 * b2 - b1 * a2))
    # find p0: set one coordinate to 0 where the 2x2 minor is nonzero
    p0 = None
    for drop in range(3):
        idx = [i for i in range(3) if i != drop]
        M = sp.Matrix([[k1[i] for i in idx], [k2[i] for i in idx]])
        if M.det() != 0:
            sol = M.solve(sp.Matrix([d1, d2]))
            p0 = [Fr(0)] * 3
            p0[idx[0]] = Fr(int(sol[0].p), int(sol[0].q)); p0[idx[1]] = Fr(int(sol[1].p), int(sol[1].q))
            break
    if p0 is None:
        raise ValueError("planes parallel")
    # |p0 + t u|^2 = N:  (u.u) t^2 + 2 (p0.u) t + (p0.p0 - N) = 0
    A = sum(x * x for x in u); Bq = 2 * sum(p * x for p, x in zip(p0, u)); C = sum(p * p for p in p0) - N
    disc = Bq * Bq - 4 * A * C
    if disc < 0:
        raise ValueError("no real intersection")
    # sqrt(disc) = (r/s) sqrt(core)
    num, den = disc.numerator, disc.denominator
    core = _squarefree(num * den)
    # disc = (num/den) = core * m^2 with m rational: m^2 = disc/core
    m2 = disc / core
    mnum, mden = math.isqrt(m2.numerator), math.isqrt(m2.denominator)
    assert mnum * mnum == m2.numerator and mden * mden == m2.denominator, "sqrt extraction failed"
    m = Fr(mnum, mden)
    d = core if core != 0 else 1
    best = None
    for s in (1, -1):
        # t = (-B + s m sqrt(core)) / (2A)
        t = QF(-Bq / (2 * A), s * m / (2 * A), d)
        pt = [QF(p, 0, d) + t * QF(x, 0, d) for p, x in zip(p0, u)]
        fl = np.array([float(c) for c in pt]) / math.sqrt(N)
        err = np.linalg.norm(fl - np.asarray(target))
        if best is None or err < best[0]:
            best = (err, pt)
    return best[1], best[0]


def certify_lattice(points3d, N, centre_xyz):
    """points3d: integer points on |x|^2 = N; centre_xyz: float unit vector (target).  Returns the
    exact circle count of the stereographic projection from the exact centre."""
    planes = LS.planes_exact(points3d)
    keys = list(planes.keys())
    # float degrees to pick two planes through the centre
    c = np.asarray(centre_xyz) * math.sqrt(N)
    res = [abs(k[0] * c[0] + k[1] * c[1] + k[2] * c[2] - k[3]) / math.sqrt(k[0] ** 2 + k[1] ** 2 + k[2] ** 2) for k in keys]
    thr = [i for i in range(len(keys)) if res[i] < 1e-6]
    if len(thr) < 2:
        return dict(ok=False, reason=f"centre lies on {len(thr)} planes (need 2 for an exact centre)")
    # choose two non-parallel ones
    Q = None
    for i, j in itertools.combinations(thr, 2):
        try:
            Q, err = exact_sphere_centre(planes, keys[i], keys[j], N, centre_xyz)
            break
        except ValueError:
            continue
    if Q is None:
        return dict(ok=False, reason="could not intersect planes")
    # exact degree of Q
    through = []
    for k in keys:
        v = QF(k[0], 0, Q[0].d) * Q[0] + QF(k[1], 0, Q[0].d) * Q[1] + QF(k[2], 0, Q[0].d) * Q[2] - QF(k[3], 0, Q[0].d)
        if v.is_zero():
            through.append(k)
    # Q must not be a configuration point
    for p in points3d:
        if all((Q[i] - QF(p[i], 0, Q[0].d)).is_zero() for i in range(3)):
            return dict(ok=False, reason="centre is a configuration point")
    n = len(points3d)
    degenerate = any(len(s) == n for s in planes.values())
    circles = len(planes) - len(through)
    return dict(ok=True, n=n, blocks=len(planes), lines=len(through), circles=circles, degenerate=degenerate,
                centre_exact=[repr(q) for q in Q], centre_float_err=err,
                circle_sizes=sorted(len(planes[k]) for k in keys if k not in set(through)),
                line_sizes=sorted(len(planes[k]) for k in through), field_disc=Q[0].d)


# ---------------------------------------------------------------- planar route
def exact_planar_centre(pts_sym, centre_float, radicands):
    """pts_sym: sympy planar points (may include 'inf'); centre_float: (x,y) float.  Finds two blocks
    through the centre and intersects them exactly.  Returns (O_sympy, extra radicand or None)."""
    fin = [p for p in pts_sym if p != 'inf']
    F = [(float(p[0]), float(p[1])) for p in fin]
    # float blocks through the centre
    cx, cy = centre_float
    cand = []
    for i, j, k in itertools.combinations(range(len(F)), 3):
        a, b, c = F[i], F[j], F[k]
        d = 2 * (a[0] * (b[1] - c[1]) + b[0] * (c[1] - a[1]) + c[0] * (a[1] - b[1]))
        if abs(d) < 1e-9:
            # line
            dx, dy = b[0] - a[0], b[1] - a[1]
            if abs((cx - a[0]) * dy - (cy - a[1]) * dx) < 1e-7 * (1 + abs(dx) + abs(dy)):
                cand.append(('L', (i, j)))
        else:
            a2 = a[0] ** 2 + a[1] ** 2; b2 = b[0] ** 2 + b[1] ** 2; c2 = c[0] ** 2 + c[1] ** 2
            ux = (a2 * (b[1] - c[1]) + b2 * (c[1] - a[1]) + c2 * (a[1] - b[1])) / d
            uy = (a2 * (c[0] - b[0]) + b2 * (a[0] - c[0]) + c2 * (b[0] - a[0])) / d
            r = math.hypot(a[0] - ux, a[1] - uy)
            if abs(math.hypot(cx - ux, cy - uy) - r) < 1e-7 * (1 + r):
                cand.append(('C', (i, j, k)))
    if len(cand) < 2:
        return None
    x, y = sp.symbols('x y')
    def eq_of(c):
        if c[0] == 'L':
            i, j = c[1]; a, b = fin[i], fin[j]
            return (b[0] - a[0]) * (y - a[1]) - (b[1] - a[1]) * (x - a[0])
        i, j, k = c[1]; a, b, cc = fin[i], fin[j], fin[k]
        M = sp.Matrix([[x ** 2 + y ** 2, x, y, 1], [a[0] ** 2 + a[1] ** 2, a[0], a[1], 1], [b[0] ** 2 + b[1] ** 2, b[0], b[1], 1], [cc[0] ** 2 + cc[1] ** 2, cc[0], cc[1], 1]])
        return sp.expand(M.det())
    for c1, c2 in itertools.combinations(cand, 2):
        try:
            sols = sp.solve([eq_of(c1), eq_of(c2)], [x, y], dict=True)
        except Exception:
            continue
        for s in sols:
            X = sp.nsimplify(s[x]); Y = sp.nsimplify(s[y])
            if not (X.is_real and Y.is_real):
                continue
            if abs(float(X) - cx) < 1e-6 and abs(float(Y) - cy) < 1e-6:
                return (sp.radsimp(X), sp.radsimp(Y))
    return None


def certify_planar(planar_strs, radicands, centre_float):
    pts = []
    for s in planar_strs:
        if s == 'inf':
            pts.append('inf')
        else:
            a, b = s.strip('()').split(',')
            pts.append((sp.sympify(a), sp.sympify(b)))
    O = exact_planar_centre(pts, centre_float, radicands)
    if O is None:
        return dict(ok=False, reason="no exact centre found")
    # collect radicands appearing in O
    rads = set(radicands)
    for e in O:
        for pw in e.atoms(sp.Pow):
            if pw.exp == sp.Rational(1, 2) and pw.base.is_Rational:
                rads.add(int(pw.base.p * pw.base.q))
    try:
        r = certify(pts, O_sympy=O, radicands=tuple(sorted(rads)))
    except Exception as e:
        return dict(ok=False, reason=f"certify failed: {e}", O=[str(o) for o in O])
    r['ok'] = True; r['O'] = [str(o) for o in O]; r['coords'] = [(str(a), str(b)) for a, b in r['coords']]
    return r


def certify_record(rec):
    ex = rec.get('exact')
    if ex is None:
        return dict(ok=False, reason="no exact data")
    if 'points3d' in ex:
        # centre: float unit vector; if the centre is a universe point ('point', i) the record's
        # best_centre_xyz is the re-evaluated best centre anyway
        return certify_lattice(ex['points3d'], ex['N'], rec['best_centre_xyz'])
    # planar: best_centre_xyz is a sphere point -> planar float centre via stereographic projection
    o = np.asarray(rec['best_centre_xyz'])
    if abs(1 - o[2]) < 1e-9:
        # centre = infinity: the planar set itself
        planar = ex['planar']
        if 'inf' in planar:
            return dict(ok=False, reason="centre = inf with inf in the set")
        pts = []
        for s in planar:
            a, b = s.strip('()').split(','); pts.append((sp.sympify(a), sp.sympify(b)))
        r = certify(pts, radicands=tuple(ex['radicands'])); r['ok'] = True; r['O'] = 'inf'
        r['coords'] = [(str(a), str(b)) for a, b in r['coords']]
        return r
    cf = (o[0] / (1 - o[2]), o[1] / (1 - o[2]))
    return certify_planar(ex['planar'], ex['radicands'], cf)


if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else 'runs/records.jsonl'
    recs = [json.loads(l) for l in open(path)]
    out = []
    for rec in recs:
        r = certify_record(rec)
        tag = "OK" if r.get('ok') else "FAIL"
        print(f"[{tag}] {rec['universe']} n={rec['n']} claimed={rec['count']} exact={r.get('circles')} f={rec['formula']} "
              f"{'' if r.get('ok') else r.get('reason')} sizes={r.get('circle_sizes')} lines={r.get('line_sizes')}", flush=True)
        out.append(dict(universe=rec['universe'], n=rec['n'], claimed=rec['count'], result=r))
    with open('runs/certified.json', 'w') as fh:
        json.dump(out, fh, indent=1, default=str)
