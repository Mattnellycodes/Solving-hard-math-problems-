#!/usr/bin/env python3
"""c2_exact_linesets.py -- exact proof that no realisation of structure C-2 has a point O lying on >= 10 blocks.

Facts used (established in analyze_C2.py / c2_torsion.py): every realisation of C-2 is Moebius-equivalent to
   a_j = zeta^{s_j},  b_k = r * zeta10^{t_k}   (zeta = e^{2 pi i/5}, zeta10 = e^{i pi/5} = -zeta^3, 0 < r < 1, r real),
where (s, t) runs over the torsion labellings listed by c2_torsion.py.  If a point O (not in P) lies on >= 10 blocks,
these blocks pairwise share <= 1 point of P and form one of the 31 line sets computed by the enumerator (all
sets of >= 10 pairwise <=1-intersecting blocks satisfying the line caps, which a real line structure obeys).
Aut(C-2) (order 40) has 5 orbits on these line sets; a relabelling by an automorphism maps realisations to
realisations, so it suffices to test the 5 orbit representatives against ALL torsion labellings.

Test: with u = O, v = conj(O) as independent unknowns and z = zeta an unknown with Phi_5(z) = 0, the condition
"O on the circle through p, q, s" is  (u - q)(p - s) conj((v ... )) ...  i.e. cross-ratio(O; p, q, s) equals its
conjugate, a polynomial in u, v, r, z.  For a line set L we form the ideal generated by these polynomials for all
blocks of L, Phi_5(z), and the saturation (Rabinowitsch) of the non-degeneracy r(1 - r)(1 + r) * prod(O - points) != 0
(r = +-1 would put the second pentagon on the circle of the first; negative r is the labelling t -> t + 5).
Groebner basis (1)  =>  no complex solution at all  =>  no real realisation with O on all blocks of L.
If a basis is not (1) we print it for inspection (then a further real-root analysis would be needed)."""
import sys, json, itertools, time
import sympy as sp
sys.path.insert(0, '.')
from c2_torsion import torsion_solutions

z, r, u, v, w = sp.symbols('z r u v w')
PHI5 = z ** 4 + z ** 3 + z ** 2 + z + 1


def red(e):
    """reduce a polynomial expression modulo Phi_5(z)."""
    return sp.rem(sp.expand(e), PHI5, z)


def conj(e):
    """complex conjugation: z -> z^4 (= 1/z), u <-> v, r real."""
    return red(sp.expand(e).subs({z: z ** 4, u: w}).subs({v: u}).subs({w: v}))


def zeta10(t):
    """e^{i pi t/5} as a polynomial in z:  e^{i pi/5} = -z^3."""
    return red((-z ** 3) ** t)


def point(label, s_ang, t_ang, A, B):
    if label in A:
        return zeta10(s_ang[A.index(label)])
    return red(r * zeta10(t_ang[B.index(label)]))


def on_circle(O_u, p, q, s):
    """polynomial condition that O = (u, v) lies on the circle through p, q, s:  cr = conj(cr)."""
    N = (u - q) * (p - s); D = (u - s) * (p - q)
    return red(N * conj(D) - conj(N) * D)


def test_line_set(L, s_ang, t_ang, A, B, blocks_by_set, verbose=True):
    eqs = [PHI5]
    pts = {lab: point(lab, s_ang, t_ang, A, B) for lab in range(10)}
    for l in L:
        p, q, s = [pts[x] for x in sorted(l)[:3]]
        eqs.append(on_circle(u, p, q, s))
    nondeg = r * (1 - r) * (1 + r)          # r = 0: B collapses; r = +-1: B lies on the circle A (degenerate)
    for lab in range(10):
        nondeg *= (u - pts[lab])
    eqs.append(red(sp.expand(nondeg * w - 1)))
    t0 = time.time()
    G = sp.groebner(eqs, w, u, v, r, z, order='grevlex')
    trivial = list(G.exprs) == [1]
    if verbose:
        print(f"      labelling s={s_ang} t={t_ang}: Groebner basis {'(1) -> impossible' if trivial else G.exprs}"
              f"  [{time.time() - t0:.1f}s]", flush=True)
    return trivial


def collinear(p, q, s):
    """polynomial condition that p, q, s are collinear: Im((q-p) conj(s-p)) = 0."""
    d1 = q - p; d2 = s - p
    return red(d1 * conj(d2) - conj(d1) * d2)


def test_line_set_infinity(L, s_ang, t_ang, A, B, verbose=True):
    """the case O = infinity of the normal form: all blocks of L are straight lines (collinear point sets)."""
    eqs = [PHI5]
    pts = {lab: point(lab, s_ang, t_ang, A, B) for lab in range(10)}
    for l in L:
        p, q, s = [pts[x] for x in sorted(l)[:3]]
        eqs.append(collinear(p, q, s))
    eqs.append(red(sp.expand(r * (1 - r) * (1 + r) * w - 1)))
    t0 = time.time()
    G = sp.groebner(eqs, w, r, z, order='grevlex')
    trivial = list(G.exprs) == [1]
    if verbose:
        print(f"      [O = infinity] labelling s={s_ang} t={t_ang}: Groebner basis "
              f"{'(1) -> impossible' if trivial else G.exprs}  [{time.time() - t0:.1f}s]", flush=True)
    return trivial


